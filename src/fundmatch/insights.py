def _words(text: str) -> list[str]:
    return (text or "").split()


def _has(text: str, needles: tuple[str, ...]) -> list[str]:
    low = f" {(text or '').lower()} "
    found = []
    for needle in needles:
        if needle == "%":
            if "%" in low or "per cent" in low:
                found.append("%")
            continue
        pattern = r"\b" + re.escape(needle)
        if re.search(pattern, low):
            found.append(needle)
    return found


def abstract_checklist(engine, title: str, abstract: str) -> dict:
    """Rule-based drafting checks. Each check shows the words that triggered it.

    This is a writing aid. It does not predict funding success and is not trained
    on outcomes; it only reports whether common proposal elements are present.
    """
    text = proposal_text(title, abstract)
    words = _words(text)
    items: list[dict] = []
    for key, label, needles, why in CHECKS:
        found = _has(text, needles)
        items.append({
            "id": key,
            "label": label,
            "status": "met" if found else "missing",
            "evidence": ", ".join(dict.fromkeys(found))[:120] if found else "No matching wording found.",
            "why": why,
        })
    # Length: the engine refuses <30 words; >=100 gives the matcher more evidence.
    n = len(words)
    items.append({
        "id": "length",
        "label": "Enough detail to score",
        "status": "met" if n >= 100 else ("partial" if n >= 30 else "missing"),
        "evidence": f"{n} words (the matcher needs 30; 100+ gives it more evidence).",
        "why": "Short text gives the model few terms, so its probabilities rest on less evidence.",
    })
    sentences = [s for s in SENTENCE_RE.split(abstract or "") if s.strip()]
    avg = (sum(len(s.split()) for s in sentences) / len(sentences)) if sentences else 0.0
    items.append({
        "id": "readability",
        "label": "Sentences are a readable length",
        "status": "met" if 0 < avg <= 28 else ("partial" if avg <= 36 else "missing"),
        "evidence": f"Average {avg:.0f} words per sentence over {len(sentences)} sentences (aim for 28 or fewer).",
        "why": "Panels skim. Long sentences hide the key claim.",
    })
    recognised = int(engine.vectorize([mask_funders(text)]).nnz) if text else 0
    items.append({
        "id": "vocabulary",
        "label": "Uses specific research vocabulary",
        "status": "met" if recognised >= 40 else ("partial" if recognised >= 15 else "missing"),
        "evidence": f"{recognised} distinct words and word-pairs match the 113k-award model vocabulary.",
        "why": "Specific terms are what the matcher (and a reviewer) uses to place the idea.",
    })
    met = sum(1 for item in items if item["status"] == "met")
    partial = sum(1 for item in items if item["status"] == "partial")
    return {
        "items": items,
        "met": met,
        "partial": partial,
        "total": len(items),
        "note": (
            "Rule-based writing checks that show the matching words. They are not a prediction of "
            "funding success and were not trained on funding outcomes."
        ),
    }


def reliability(engine, analysis) -> dict:
    """How far to trust the top probability, using the published held-out test profile."""
    if not analysis or not analysis.ok or not analysis.councils:
        return {}
    probs = [row.probability for row in analysis.councils]
    top = probs[0]
    second = probs[1] if len(probs) > 1 else 0.0
    bins = engine.model_info.get("accuracy_by_confidence", {})
    chosen_label, chosen_acc = None, None
    for label, acc in bins.items():
        low, high = (float(x) for x in label.strip("(]").split(","))
        if low < top <= high or (top == 0 and low == 0):
            chosen_label, chosen_acc = label, float(acc)
            break
    margin = top - second
    if margin >= 0.5:
        margin_note = "The leader is far ahead of the runner-up."
    elif margin >= 0.2:
        margin_note = "The leader is clearly ahead, but read the runner-up too."
    else:
        margin_note = "The top two are close. Treat this as a two-council idea."
    return {
        "probability": top,
        "runner_up": analysis.councils[1].council if len(analysis.councils) > 1 else None,
        "runner_up_probability": second,
        "margin": round(margin, 4),
        "margin_note": margin_note,
        "bin": chosen_label,
        "bin_test_accuracy": chosen_acc,
        "set90": list(analysis.conformal_set_90),
        "set95": list(analysis.conformal_set_95),
        "entropy_normalized": analysis.entropy_normalized,
        "test_top3": float(engine.model_info.get("test_top3", 0.0)),
        "note": (
            "Accuracy-by-confidence comes from the held-out test split in model_info.json. "
            "It describes how often the model's top council matched the real lead funder, "
            "not whether a proposal would be funded."
        ),
    }


def decision_drivers(engine, title: str, abstract: str, council: str | None = None, k: int = 10) -> dict:
    """Word-level drivers for one council, in temperature-scaled logit points."""
    text = proposal_text(title, abstract)
    if not text:
        return {"council": council, "rows": []}
    if council is None:
        probs = engine.predict_proba_masked(mask_funders(text))
        council = engine.classes[int(np.argmax(probs))]
    explanation = engine.explain_council(title, abstract, council, k=k)
    t = float(engine.temperature)
    rows = [
        {"term": item.feature, "points": round(item.contribution / t, 4), "direction": "toward"}
        for item in explanation.positive
    ] + [
        {"term": item.feature, "points": round(item.contribution / t, 4), "direction": "away"}
        for item in explanation.negative
    ]
    return {
        "council": council,
        "rows": rows,
        "note": (
            "Each bar is the word's TF-IDF weight in your text times the model's coefficient for this "
            "council, divided by the calibration temperature. Positive bars push the council's score up."
        ),
    }


def _title_terms(title: str) -> set[str]:
    tokens = [tok for tok in TOKEN_RE.findall(html.unescape(title or "").lower()) if len(tok) > 3 and tok not in _STOP]
    terms = set(tokens)
    terms.update(f"{a} {b}" for a, b in zip(tokens, tokens[1:]))
    return terms


def keyword_radar(engine, title: str, abstract: str, council: str | None = None, neighbours: int = 50, k: int = 12) -> dict:
    """Terms common in the nearest funded titles, with the model's weight for the council.

    ``in_text`` says whether the draft already uses the term. Only add a term if it
    is true of the work.
    """
    text = proposal_text(title, abstract)
    if not text:
        return {"council": council, "suggest": [], "already": [], "neighbours": 0}
    masked = mask_funders(text)
    if council is None:
        council = engine.classes[int(np.argmax(engine.predict_proba_masked(masked)))]
    rrf, _svd, _lex, _q = engine._search(masked)
    idx = engine._top(rrf, neighbours)
    titles = engine.frame.iloc[idx]["title"].fillna("").astype(str).tolist()
    counts: Counter[str] = Counter()
    for t in titles:
        counts.update(_title_terms(t))
    low = f" {text.lower()} "
    class_index = engine.classes.index(council)
    suggest, already = [], []
    for term, count in counts.most_common(400):
        if count < 2 or term not in engine.index:
            continue
        weight = float(engine.coef[class_index, engine.index[term]])
        row = {"term": term, "titles": int(count), "of": len(titles), "weight": round(weight, 4)}
        if re.search(r"\b" + re.escape(term) + r"\b", low):
            already.append(row)
        elif weight > 0:
            suggest.append(row)
    suggest.sort(key=lambda r: (r["titles"], r["weight"]), reverse=True)
    already.sort(key=lambda r: r["titles"], reverse=True)
    return {
        "council": council,
        "suggest": suggest[:k],
        "already": already[:k],
        "neighbours": len(titles),
        "note": (
            "Counts are how many of the nearest funded titles use the term. Weight is the deployed "
            "model's coefficient for the council (positive pushes toward it). Use a term only if it is true of your work."
        ),
    }


def compare_two(engine, a: dict, b: dict, neighbours: int = 30) -> dict:
    """Side-by-side for two ideas: probabilities, semantic closeness and shared precedents."""
    out = {"ok": False, "a": None, "b": None}
    results = []
    for item in (a, b):
        res = engine.analyze(item.get("title", ""), item.get("abstract", ""), top_k=neighbours, cpih=True)
        results.append(res)
    if not all(r.ok for r in results):
        out["errors"] = [e for r in results for e in r.errors]
        return out
    vectors, ids = [], []
    for item, res in zip((a, b), results):
        _rrf, _svd, _lex, q = engine._search(mask_funders(proposal_text(item.get("title", ""), item.get("abstract", ""))))
        vectors.append(np.asarray(q, dtype=np.float64))
        ids.append({p.project_id for p in res.similar})
    na, nb = np.linalg.norm(vectors[0]), np.linalg.norm(vectors[1])
    cosine = float(vectors[0] @ vectors[1] / (na * nb)) if na and nb else 0.0
    union = ids[0] | ids[1]
    jaccard = len(ids[0] & ids[1]) / len(union) if union else 0.0
    prob = {name: [0.0, 0.0] for name in engine.classes}
    for col, res in enumerate(results):
        for row in res.councils:
            prob[row.council][col] = row.probability
    rows = [{"council": c, "idea_a": v[0], "idea_b": v[1], "difference": round(v[0] - v[1], 6)} for c, v in prob.items()]
    rows.sort(key=lambda r: max(r["idea_a"], r["idea_b"]), reverse=True)

    def summary(res):
        return {
            "top_council": res.top_council,
            "probability": res.councils[0].probability,
            "confidence": res.confidence,
            "set90": res.conformal_set_90,
            "novelty": (res.novelty or {}).get("band"),
            "median_gbp_2026": res.award.median if res.award else None,
            "priced_neighbours": res.award.n_positive if res.award else 0,
        }

    return {
        "ok": True,
        "a": summary(results[0]),
        "b": summary(results[1]),
        "councils": rows,
        "semantic_cosine": round(cosine, 4),
        "shared_precedents": len(ids[0] & ids[1]),
        "neighbour_jaccard": round(jaccard, 4),
        "neighbours": neighbours,
        "note": (
            "Semantic cosine compares the two ideas in the 64-dimension abstract map (1 = same direction). "
            f"Shared precedents counts projects that appear in both ideas' {neighbours} nearest funded projects."
        ),
    }


def filter_precedents(rows: list[dict], councils: list[str] | None = None, years: tuple[int, int] | None = None,
                      award: tuple[float, float] | None = None, priced_only: bool = False) -> list[dict]:
    """Pure filter used by the precedent explorer. Rows are SimilarProject dicts."""
    out = []
    for row in rows:
        if councils and row.get("lead_funder") not in councils:
            continue
        year = row.get("start_year")
        if years and (year is None or not (years[0] <= int(year) <= years[1])):
            continue
        amount = float(row.get("award_gbp") or 0.0)
        if priced_only and amount <= 0:
            continue
        if award and amount > 0 and not (award[0] <= amount <= award[1]):
            continue
        out.append(row)
    return out


def neighbourhood_pulse(engine, title: str, abstract: str) -> dict:
    """Council mix and recent share inside the 200 nearest funded projects."""
    text = proposal_text(title, abstract)
    if len(text.split()) < 3:
        return {}
    _rrf, svd, _lex, _q = engine._search(mask_funders(text))
    idx = np.argsort(-svd)[:200]
    part = engine.frame.iloc[idx]
    mix = part["lead_funder"].astype(str).value_counts()
    years = part["start_year"].dropna().astype(int)
    since = int(years.max()) - 4 if len(years) else None
    recent_share = float((years >= since).mean()) if since is not None else None
    return {
        "neighbours": int(len(idx)),
        "council_mix": [{"council": c, "projects": int(n), "share": round(n / len(idx), 4)} for c, n in mix.items()],
        "recent_from": since,
        "recent_share": None if recent_share is None else round(recent_share, 4),
        "years": [int(years.min()), int(years.max())] if len(years) else None,
    }



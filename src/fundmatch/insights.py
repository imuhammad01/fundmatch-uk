"""V5 insight layer: explainability, reliability, honest draft checks, keyword radar,
two-idea comparison, precedent explorer and a PDF brief.

Everything here is computed from the deployed TF-IDF + logistic-regression model,
the published held-out test profile in ``artifacts/model_info.json`` and the
113,233-row GtR metadata table. Nothing is generated by a language model and no
number is invented: if the data cannot support a statement, the function says so.
"""


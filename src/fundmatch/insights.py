_PDF_MAP = {
    "\u2013": "-", "\u2014": "-", "\u2212": "-", "\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"',
    "\u2026": "...", "\u2265": ">=", "\u2264": "<=", "\u2192": "->", "\u2190": "<-", "\u00d7": "x",
    "\u2022": "-", "\u25c8": "*", "\u2726": "*", "\u00a0": " ",
}


def _latin(text) -> str:
    value = str(text if text is not None else "")
    for key, rep in _PDF_MAP.items():
        value = value.replace(key, rep)
    return value.encode("latin-1", "replace").decode("latin-1")


def pdf_brief(title: str, abstract: str, analysis, checklist: dict | None = None,
              drivers: dict | None = None, radar: dict | None = None, app_name: str = "ScholarPulse UK",
              version: str = "") -> bytes:
    """A one-to-three page PDF of the live analysis. Lazy-imports fpdf2 so start-up memory is unchanged."""
    from fpdf import FPDF

    pdf = FPDF(format="A4")
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.set_margins(15, 15, 15)
    pdf.add_page()
    width = pdf.w - pdf.l_margin - pdf.r_margin

    def heading(text, size=13):
        pdf.ln(2)
        pdf.set_font("Helvetica", "B", size)
        pdf.set_text_color(15, 118, 110)
        pdf.multi_cell(width, 7, _latin(text), new_x="LMARGIN", new_y="NEXT")
        pdf.set_text_color(20, 20, 20)

    def para(text, size=9.5, style=""):
        pdf.set_font("Helvetica", style, size)
        pdf.multi_cell(width, 5, _latin(text), new_x="LMARGIN", new_y="NEXT")

    pdf.set_font("Helvetica", "B", 18)
    pdf.set_text_color(15, 23, 42)
    pdf.cell(width, 10, _latin(f"{app_name} - funding fit brief"), new_x="LMARGIN", new_y="NEXT")
    para(f"Generated {date.today().isoformat()} {('- ' + version) if version else ''}. Source: 113,233 UKRI Gateway to Research awards (Open Government Licence v3.0).", 8.5)
    heading("Idea")
    para(title or "(untitled)", 10.5, "B")
    para((abstract or "")[:2500])
    if analysis is None or not getattr(analysis, "ok", False):
        heading("Result")
        para("The text could not be scored: " + "; ".join(getattr(analysis, "errors", []) or ["no text"]))
        return bytes(pdf.output())
    heading("Council fit (calibrated probabilities)")
    pdf.set_font("Helvetica", "", 9.5)
    for row in analysis.councils:
        pdf.cell(28, 5.5, _latin(row.council))
        pdf.cell(18, 5.5, f"{row.probability:.1%}", align="R")
        pdf.cell(width - 46, 5.5, _latin("   " + row.full_name), new_x="LMARGIN", new_y="NEXT")
    para(f"90% set: {', '.join(analysis.conformal_set_90)}   95% set: {', '.join(analysis.conformal_set_95)}", 9.5, "B")
    para(analysis.confidence_note or "")
    if analysis.novelty:
        para(f"Novelty: {analysis.novelty.get('band')}. {analysis.novelty.get('note', '')}")
    band = analysis.award
    if band and band.median is not None:
        heading("Award band among the nearest funded projects")
        para(f"P25 GBP {band.p25:,.0f}   median GBP {band.median:,.0f}   P75 GBP {band.p75:,.0f}   ({band.n_positive} priced of {band.neighbours}; {band.basis})")
        para(band.caveat, 8.5)
    if drivers and drivers.get("rows"):
        heading(f"Words that drive {drivers['council']}")
        toward = [r for r in drivers["rows"] if r["direction"] == "toward"]
        away = [r for r in drivers["rows"] if r["direction"] == "away"]
        para("Toward: " + ", ".join(f"{r['term']} (+{r['points']:.2f})" for r in toward))
        if away:
            para("Away: " + ", ".join(f"{r['term']} ({r['points']:.2f})" for r in away))
    if checklist:
        heading(f"Draft checklist - {checklist['met']} of {checklist['total']} met")
        for item in checklist["items"]:
            mark = {"met": "[x]", "partial": "[~]", "missing": "[ ]"}[item["status"]]
            para(f"{mark} {item['label']}: {item['evidence']}", 9)
        para(checklist["note"], 8)
    if radar and radar.get("suggest"):
        heading("Terms common in nearby funded titles that your draft does not use")
        para(", ".join(f"{r['term']} ({r['titles']}/{r['of']})" for r in radar["suggest"]))
        para("Only add a term if it is true of the work.", 8)
    if analysis.similar:
        heading("Nearest funded projects")
        for p in analysis.similar[:10]:
            amount = f"GBP {p.award_gbp:,.0f}" if p.award_gbp > 0 else "not priced"
            para(f"- {p.title} ({p.lead_funder}, {p.start_year or 'n/a'}, {amount}) {p.gtr_url}", 8.5)
    heading("Live calls")
    for row in analysis.councils[:3]:
        para(f"{row.council}: {row.funding_finder_url}", 8.5)
    heading("Caveats", 11)
    para(
        "Council probabilities describe which UKRI council has funded similar text in the past. They are not a "
        "prediction of funding success. Award figures come from nearby historical grants and are not a quote. "
        "Check eligibility and open calls on the UKRI Funding Finder.", 8.5,
    )
    return bytes(pdf.output())
